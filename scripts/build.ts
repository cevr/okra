// Local build only: never create or replace an installed link.
import { spawn } from "node:child_process";
import { chmod, mkdir } from "node:fs/promises";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
await mkdir(join(root, "bin"), { recursive: true });
async function run(command: string, args: string[]) {
  const child = spawn(command, args, { cwd: root, stdio: "inherit", detached: true });
  let active = true;
  const stop = () => {
    if (active && child.pid) {
      try {
        process.kill(-child.pid, "SIGTERM");
      } catch {
        /* already exited */
      }
    }
  };
  for (const signal of ["SIGINT", "SIGTERM", "SIGHUP"] as const) process.on(signal, stop);
  try {
    const code = await new Promise<number>((resolve, reject) => {
      child.once("error", reject);
      child.once("close", (status) => resolve(status ?? 1));
    });
    if (code !== 0) throw new Error(`${command} exited ${code}`);
  } finally {
    stop();
    active = false;
    for (const signal of ["SIGINT", "SIGTERM", "SIGHUP"] as const) process.off(signal, stop);
  }
}
await chmod(join(root, "bin/okra"), 0o755);
const prepare = process.argv.includes("--prepare");
if (prepare || process.argv.includes("--ergo")) {
  // The generated Ergo sources (git-ignored): the embedded guides, and the
  // root's --version line from package.json. scripts/release.ts runs
  // --prepare alone before it cross-builds.
  await run(process.execPath, ["scripts/guides.ts"]);
  const version = (await Bun.file(join(root, "package.json")).json()).version as string;
  await Bun.write(
    join(root, "ergo/cli/version.ergo"),
    `// Generated by scripts/build.ts from package.json; do not edit.\n\nlet versionLine = ${JSON.stringify(`okra v${version}`)}\n`,
  );
}
if (prepare) process.exit(0);
if (process.argv.includes("--ergo")) {
  await run(process.env.ERGO ?? "ergo", ["build", "ergo/cmd/okra", "-o", "bin/okra-ergo"]);
  // Offline parity entry: registry URLs go to a loopback fake only.
  await run(process.env.ERGO ?? "ergo", [
    "build",
    "ergo/cmd/okra-parity",
    "-o",
    "bin/okra-ergo-parity",
  ]);
} else {
  const result = await Bun.build({
    entrypoints: [join(root, "src/main.ts")],
    target: "bun",
    compile: { outfile: join(root, "bin/okra-ts"), autoloadBunfig: false },
    define: {
      __VERSION__: JSON.stringify((await Bun.file(join(root, "package.json")).json()).version),
    },
  });
  if (!result.success) throw new Error(`TypeScript build failed: ${result.logs.join("\n")}`);
}

// Build-time assets, not a second guide parser. The registered TS topics are
// the authoritative order and documents until the owner retires TS.
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { TOPICS } from "../src/how/topics";

const target = join(import.meta.dir, "../ergo/how");
await mkdir(target, { recursive: true });
const quote = (s: string) => JSON.stringify(s);
const rows = TOPICS.map(
  (topic) =>
    `\t\tTopic{Name: ${quote(topic.name)}, Summary: ${quote(topic.summary)}, Body: ${quote(topic.body)}},`,
);
await writeFile(
  join(target, "topics.ergo"),
  `// Generated by scripts/guides.ts from the registered guides. Do not edit.\nfunc All() []Topic {\n\t[]Topic{\n${rows.join("\n")}\n\t}\n}\n`,
);

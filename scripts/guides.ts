// Build-time assets: `okra how` serves the skills' SKILL.md files, in this
// order. Each topic's summary is the first sentence of its frontmatter
// description; its body is the file without the frontmatter.
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = join(import.meta.dir, "..");
const order = ["schedule", "counsel", "repo", "skills", "image", "keys"];
const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/;

function description(doc: string) {
  const match = doc.match(frontmatter);
  if (match?.[1] === undefined) return "";
  for (const line of match[1].split("\n")) {
    const at = line.indexOf(":");
    if (at !== -1 && line.slice(0, at).trim() === "description") return line.slice(at + 1).trim();
  }
  return "";
}
const firstSentence = (text: string) => (text.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? text).trim();

const quote = (s: string) => JSON.stringify(s);
const rows: string[] = [];
for (const name of order) {
  const doc = await readFile(join(root, "skills", name, "SKILL.md"), "utf8");
  const summary = firstSentence(description(doc));
  const body = doc.replace(frontmatter, "").trim();
  rows.push(`\t\tTopic{Name: ${quote(name)}, Summary: ${quote(summary)}, Body: ${quote(body)}},`);
}
const target = join(root, "ergo/how");
await mkdir(target, { recursive: true });
await writeFile(
  join(target, "topics.ergo"),
  `// Generated by scripts/guides.ts from skills/*/SKILL.md. Do not edit.\nfunc All() []Topic {\n\t[]Topic{\n${rows.join("\n")}\n\t}\n}\n`,
);

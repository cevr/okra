// Generates ergo/localzone/names.ergo: the TZ names the port reads, as Bun
// reads them. A name is a zone only if the tzdata the binary carries (Go's
// lib/time/zoneinfo.zip, the timetzdata build tag) has it, or if Bun's ICU
// reads it as a zone that the carried tzdata has (an ICU alias such as PST
// or US/Pacific-New). Each alias is measured: Bun runs with TZ=<alias> and
// with TZ=<target>, and the offsets of local wall clocks (12:00 on the 1st
// and 15th of each month, 1900-2040) must be equal, and differ from UTC's.
// The lower-case form of each alias is measured the same way, since ICU
// folds case for some ids and not others.
//
//   bun scripts/zone-names.ts [--icu=<zoneinfo64.txt>]
//
// --icu refreshes parity/icu-zone-ids.txt from ICU's zoneinfo64.txt (the
// Names table of the ICU release Bun carries). Local only; spawns Bun and
// `go env GOROOT`, no network.
import { spawnSync } from "node:child_process";
import { readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { carriedNames, goEnv, icuNames, icuNamesFile } from "../parity/zones";

const root = join(import.meta.dir, "..");
const arg = (name: string) =>
  process.argv.find((s) => s.startsWith(`--${name}=`))?.slice(name.length + 3);

const icuSource = arg("icu");
if (icuSource !== undefined) {
  const text = readFileSync(icuSource, "utf8");
  const version = /^\/\/ tz version:\s*(\S+)/m.exec(text)?.[1] ?? "?";
  const start = text.indexOf("\n Names {");
  const end = text.indexOf("\n }", start);
  if (start < 0 || end < 0) throw new Error(`no Names table in ${icuSource}`);
  const names = [...text.slice(start, end).matchAll(/"([^"]*)"/g)].map((m) => m[1]!);
  writeFileSync(
    icuNamesFile,
    `# ICU's zone ids: the Names table of zoneinfo64.txt (ICU ${process.versions.icu}, tz ${version}),\n` +
      `# read by scripts/zone-names.ts --icu=<zoneinfo64.txt>. Bun reads TZ through ICU.\n` +
      names.join("\n") +
      "\n",
  );
}

const goVersion = goEnv("GOVERSION");
const carried = carriedNames();
const carriedSet = new Set(carried);
const icu = icuNames();

const probe = `
const offs = [];
for (let y = 1900; y <= 2040; y++) for (let m = 0; m < 12; m++) for (const d of [1, 15]) offs.push(new Date(y, m, d, 12).getTime() - Date.UTC(y, m, d, 12));
console.log(JSON.stringify({ zone: Intl.DateTimeFormat().resolvedOptions().timeZone, offs: offs.join(",") }));
`;
const probeFile = join(
  process.env.OKRA_PARITY_SCRATCH ?? "/tmp/opencode",
  `zone-probe-${process.pid}.ts`,
);
writeFileSync(probeFile, probe);
const read = (tz: string) => {
  const r = spawnSync(process.execPath, [probeFile], {
    env: { PATH: process.env.PATH, TZ: tz },
    encoding: "utf8",
  });
  if (r.status !== 0) throw new Error(`bun under TZ=${tz}: ${r.stderr}`);
  return JSON.parse(r.stdout) as { zone: string; offs: string };
};
const utc = read("UTC").offs;
const byLower = new Map(carried.map((n) => [n.toLowerCase(), n]));
// An alias: an ICU id the carried data lacks, which Bun reads as a carried zone.
const lines: string[] = carried.slice();
for (const name of icu) {
  if (carriedSet.has(name)) continue;
  const r = read(name);
  if (r.offs === utc) continue; // Bun reads it as UTC (an id with no data, such as SystemV/EST5)
  const target = carriedSet.has(r.zone) ? r.zone : byLower.get(r.zone.toLowerCase());
  if (target === undefined || read(target).offs !== r.offs)
    throw new Error(`Bun reads TZ=${name} as ${r.zone}, which the carried tzdata does not match`);
  const folds = read(name.toLowerCase()).offs === r.offs;
  lines.push(`${name}${folds ? "=" : ">"}${target}`);
}
const lower = new Set<string>();
for (const l of lines) {
  const key = l.split(/[=>]/)[0]!.toLowerCase();
  if (lower.has(key)) throw new Error(`two names fold to ${key}`);
  lower.add(key);
}
writeFileSync(
  join(root, "ergo/localzone/names.ergo"),
  `// Generated by scripts/zone-names.ts (${goVersion} zoneinfo.zip, Bun ${Bun.version}, ICU ${process.versions.icu}); do not edit.\n\n` +
    `// names holds one TZ name a line: a name of the carried tzdata alone, or\n` +
    `// an ICU alias and the carried name Bun reads it as, after "=" when Bun\n` +
    `// also reads the alias in any case, after ">" when only as written.\n` +
    `let names = ${JSON.stringify(`\n${lines.join("\n")}\n`)}\n`,
);
unlinkSync(probeFile);
console.log(`ZONE NAMES: ${carried.length} carried, ${lines.length - carried.length} aliases`);
